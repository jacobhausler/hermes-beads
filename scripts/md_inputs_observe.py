#!/usr/bin/env python3
"""tests/md_inputs.txt generator — the admission deny-list's consumer input
(NEXTGEN-CI.md (d), red-team patch S4b/S4a): a .md path that test sources
reference as an INPUT forces FULL gates regardless of extension, because this
estate ships .md as runtime behavior (skills, rule files).

Mechanical law: scan this repo's test sources (tests/test_*.py, tests/test_*.mjs)
for string-literal path tokens ending in `.md`; keep a candidate iff it resolves
to a real file, relative to the repo root or to tests/. Runtime artifact names
(answer.md, summary.md, *.prompt.md written INTO run dirs) do not exist in the
tree and fall out — that is the point of the existence filter, not an accident.
Over-inclusion is the safe direction (it only ever costs a docs-only PR the
FULL pass); under-inclusion is the risk this file exists to close.

An empty list is a VALID output (the file carries only its header comments).
Regenerate with: python3 scripts/md_inputs_observe.py
"""
import argparse
import re
from pathlib import Path

TOKEN_RE = re.compile(r'[A-Za-z0-9._-]+(?:/[A-Za-z0-9._-]+)*\.md')
# literals that are outputs/tests fixtures written at runtime — even if a
# same-named file exists in the tree these are NOT inputs; keep this list empty
# unless a demonstrated false-positive appears.
EXCLUDE = set()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', default='.')
    ap.add_argument('--out', default='tests/md_inputs.txt')
    a = ap.parse_args()
    root = Path(a.root)

    found = set()
    for src in sorted((root / 'tests').glob('test_*.py')) + \
            sorted((root / 'tests').glob('test_*.mjs')):
        for tok in TOKEN_RE.findall(src.read_text(errors='replace')):
            if tok in EXCLUDE:
                continue
            for cand in (root / tok, root / 'tests' / tok):
                if cand.is_file():
                    found.add(str(cand.relative_to(root)))
    lines = ['# Generated by scripts/md_inputs_observe.py — do not hand-edit.',
             '# A path listed here forces FULL gates when a PR diff touches it',
             '# (estate-ci admission, deny-wins via consumer list).',
             '# Empty-but-valid: no test source references an existing .md input.']
    lines += sorted(found)
    Path(a.out).write_text('\n'.join(lines) + '\n')
    print(f'md_inputs_observe: {len(found)} md input path(s) -> {a.out}')


if __name__ == '__main__':
    main()
